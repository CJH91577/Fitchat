import { todayKey } from './dates'

/**
 * 演示里的「今天」。
 *
 * 由**构建时**确定一次，而不是每次渲染现算：静态导出后没有服务端，
 * 「今天」只能冻在构建那一刻；而且服务端与浏览器必须拿到同一个值，
 * 否则客户端组件在浏览器里重新求值会与预渲染结果不符。
 *
 * NEXT_PUBLIC_TODAY 由 next.config.ts 在构建时注入（两端都会内联成同一个
 * 字面量）。保留 fallback 是为了测试环境——测试读不到那个变量，
 * 于是退回到「此刻的真实日期」。
 *
 * 代价：日期随构建时间冻结，需要定时重建来刷新（见 DEPLOY.md）。
 *
 * 它是**演示时钟**，不是数据。单独放一个文件，是为了让
 * 「页面还在读假数据」与「页面需要一个『今天』」在代码上一眼可辨：
 * 页面已经全部改读数据库，唯一还需要从演示侧拿的就是这个日期。
 */
export const TODAY = process.env.NEXT_PUBLIC_TODAY || todayKey()
