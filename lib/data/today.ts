import { todayKey } from './dates'

/**
 * 「今天」。
 *
 * **按请求计算，不是构建期常量**——这是从静态导出换成服务端渲染之后最重要的一处
 * 语义变化。以前它由 next.config.ts 在构建时注入（NEXT_PUBLIC_TODAY），代价是
 * 日期被冻在构建那一刻：站点不会自己往前翻页，必须靠每晚重新构建来续命。
 * 现在服务端每次渲染都会重新取当前日期，那套定时重建机制可以彻底退休。
 *
 * 它是**演示时钟**，不是数据。单独放一个文件，是为了让
 * 「页面还在读假数据」与「页面需要一个『今天』」在代码上一眼可辨。
 *
 * 时区固定为北京时间（见 todayKey）——部署在 UTC 的服务器上时，
 * 按运行环境取日期会在北京时间凌晨把「今天」算成昨天。
 */
export function today(): string {
  return todayKey()
}
